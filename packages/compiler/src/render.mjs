export function renderReminder(ast, protocolVersion) {
  const rules = reminderRules(ast);
  const head = `PRUMO PROTOCOL ACTIVE. Protocol ${protocolVersion}, ${ast.rules.length} rules (${ast.rules[0].id} to ${ast.rules.at(-1).id}); every rule has a stable id and the kernel is normative.`;
  const body = rules.map(rule => `${kernelText(rule)} (${rule.id})`).join(" ");
  return `${head} ${body}`;
}

