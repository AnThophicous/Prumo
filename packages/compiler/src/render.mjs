export function renderReadmeBlock(manifest) {
  const targets = manifest.targets.map(target => `\`${target}\``).join(", ");
  return `${README_BEGIN}
The protocol contains **${manifest.ruleCount} citable rules** (\`${manifest.ruleRange.first}\` to \`${manifest.ruleRange.last}\`) in ${manifest.sections.filter(section => section.number !== undefined).length} sections, compiled into a kernel of about ${manifest.kernel.tokens} tokens and ${manifest.chapters.length} chapters. Protocol version \`${manifest.protocolVersion}\`, source \`sha256:${manifest.sourceHash.slice(0, 12)}\`. Supported targets: ${targets}.
${README_END}`;
}

export function buildManifest(ast, { protocolVersion, sourceHash, kernelBody, reminder, targets }) {
  const rules = ast.rules.map(rule => {
    const chapter = CHAPTERS.find(entry => entry.sections.includes(rule.sectionNumber));
    return {
      id: rule.id,
      section: rule.sectionNumber,
      subsection: rule.subsection,
      title: rule.title ?? kernelText(rule).replace(/\.$/, "").slice(0, 80),
      tier: rule.kernel ? "kernel" : "chapter",
      reminder: rule.reminder,
      critical: rule.critical,
      chapter: chapter?.id,
      triggers: chapter ? chapter.triggers.map(trigger => trigger.id) : [],
      references: rule.references,
      enforcement: rule.enforcement,
      evalSuite: rule.evalSuite,
      source: { file: "content/PRUMO.md", line: rule.line }
    };
  });
  const kernelIds = rules.filter(rule => rule.tier === "kernel").map(rule => rule.id);
  return {
    generatedBy: "Prumo protocol compiler",
    protocolVersion,
    sourceHash,
    ruleCount: rules.length,
    ruleRange: { first: rules[0].id, last: rules.at(-1).id },
    sections: ast.sections.map(section => ({ number: section.number, appendix: section.appendix, title: section.title, line: section.line, rules: section.ruleIds })),
    chapters: CHAPTERS.map(chapter => ({
      id: chapter.id,
      title: chapter.title,
      sections: chapter.sections,
      defaultLoad: chapter.defaultLoad,
      nonSuppressible: Boolean(chapter.nonSuppressible),
      rules: rules.filter(rule => rule.chapter === chapter.id).map(rule => rule.id),
      tokens: estimateTokens(renderChapter(ast, chapter, protocolVersion, sourceHash)),
      triggers: chapter.triggers
    })),
    kernel: { rules: kernelIds, tokens: estimateTokens(kernelBody), budget: KERNEL_TOKEN_BUDGET },
    reminder: { rules: rules.filter(rule => rule.reminder).map(rule => rule.id), text: reminder, tokens: estimateTokens(reminder) },
    precedence: ["security and privacy", "data integrity", "the user's explicit decision", "an existing public contract", "the active specification", "the repository's convention", "Prumo's own preference"],
    critical: rules.filter(rule => rule.critical).map(rule => rule.id),
    coverage: summarizeCoverage(rules),
    targets,
    rules
  };
}

export function summarizeCoverage(rules) {
  const byCategory = {};
  for (const rule of rules) byCategory[rule.enforcement] = (byCategory[rule.enforcement] ?? 0) + 1;
  return byCategory;
}

export function renderCoverageReport(manifest) {
  const lines = [
    `# Protocol coverage — protocol ${manifest.protocolVersion}`,
    "",
    "Categories: ENFORCED (a mechanism prevents the violation), DETERMINISTICALLY_TESTED (a test in this repository checks it), BEHAVIOR_EVAL (an eval suite judges agent transcripts), DOCUMENTARY (descriptive text), MANUAL (prompted only; verified by human review). Prompted is not enforced (PRU-261).",
    "",
    "| Category | Rules |",
    "|---|---|"
  ];
  for (const [category, count] of Object.entries(manifest.coverage).sort()) lines.push(`| ${category} | ${count} |`);
  lines.push("", "| Rule | Category | Eval suite | Critical |", "|---|---|---|---|");
  for (const rule of manifest.rules) lines.push(`| ${rule.id} | ${rule.enforcement} | ${rule.evalSuite ?? ""} | ${rule.critical ? "yes" : ""} |`);
  return `${lines.join("\n")}\n`;
}
