export const MANAGED_BEGIN = "<!-- PRUMO:BEGIN";
export const MANAGED_END = "<!-- PRUMO:END -->";
export const README_BEGIN = "<!-- PRUMO:GENERATED:BEGIN -->";
export const README_END = "<!-- PRUMO:GENERATED:END -->";
export const KERNEL_TOKEN_BUDGET = 2500;
export const CHAPTER_PATH_HINT = "~/.prumo/protocol/chapters/<chapter>.md";

export function stamp(protocolVersion, sourceHash, extra = "") {
  const suffix = extra ? ` ${extra}` : "";
  return `<!-- Generated by Prumo. Protocol ${protocolVersion}. Source sha256:${sourceHash}. Do not edit: edit content/PRUMO.md and run npm run build.${suffix} -->`;
}

export function renderFullProtocol(ast, protocolVersion, sourceHash) {
  const body = stripMarkers(ast.lines.join("\n")).replace(/^<!--\s*prumo-protocol:[^\n]*-->\n/, "");
  return `${stamp(protocolVersion, sourceHash)}\n${body.trimEnd()}\n`;
}

export function identityParagraphs(ast) {
  const paragraphs = [];
  let buffer = [];
  for (const line of ast.intro) {
    if (/^(#|<!--|\*\*Contents\*\*|- Section|- Appendix|---)/.test(line)) {
      if (line.startsWith("**Contents**")) break;
      continue;
    }
    if (line.trim() === "") {
      if (buffer.length > 0) paragraphs.push(buffer.join(" "));
      buffer = [];
      continue;
    }
    buffer.push(line.trim());
  }
  if (buffer.length > 0) paragraphs.push(buffer.join(" "));
  return paragraphs.filter(paragraph => !/machine-readable markers/.test(paragraph));
}

export function routerTable(ast) {
  const bootstrap = ast.sections.find(section => section.number === 0);
  if (!bootstrap) return [];
  const lines = bootstrap.lines;
  const start = lines.findIndex(line => /^\| Situation \|/.test(line));
  if (start === -1) return [];
  const table = [];
  for (let index = start; index < lines.length && lines[index].startsWith("|"); index += 1) table.push(lines[index]);
  return table;
}

export function routerChapterIds(ast) {
  const ids = new Set();
  for (const row of routerTable(ast).slice(2)) {
    const cell = row.split("|")[2] ?? "";
    for (const match of cell.matchAll(/`([a-z-]+)`/g)) ids.add(match[1]);
  }
  return [...ids];
}

export function kernelRules(ast) {
  return ast.rules.filter(rule => rule.kernel).sort((a, b) => compareRuleIds(a.id, b.id));
}

export function reminderRules(ast) {
  return ast.rules.filter(rule => rule.reminder).sort((a, b) => compareRuleIds(a.id, b.id));
}

export function renderKernelBody(ast, protocolVersion) {
  const identity = identityParagraphs(ast);
  const rules = kernelRules(ast);
  const lines = [
    "# Prumo kernel",
    "",
    `Protocol ${protocolVersion}, ${ast.rules.length} rules (${ast.rules[0].id} to ${ast.rules.at(-1).id}). This kernel is always active. Chapters carry the rest and are loaded by the router below. Cite rules by id.`,
    "",
    ...identity,
    "",
    "## Always-on rules",
    ""
  ];
  for (const rule of rules) lines.push(`- **${rule.id}.** ${kernelText(rule)}`);
  lines.push("", "## Chapter router", "");
  lines.push(...routerTable(ast));
  lines.push(
    "",
    `Chapter files: \`${CHAPTER_PATH_HINT}\` (or under \`$PRUMO_HOME/protocol/chapters/\`). \`prumo chapter <id>\` prints one; \`prumo explain PRU-xx\` prints one rule with its chapter and related rules. The full protocol is at \`~/.prumo/protocol/full/PRUMO.md\` for audits and explicit full mode.`,
    "",
    "## State and delivery contract",
    "",
    "- Read `MapSource.md` first when it exists; keep it under the schema-2 headings and its hot-state budget; update it at the end of each block of work.",
    "- Every report states what was done, how it was verified (command and result, or \"not verified: reason\"), what was left out, known risks, and the honest grade of the delivery.",
    "- Never report a chapter as loaded without naming the trigger that fired. Never call a rule enforced when it is only prompted."
  );
  return `${lines.join("\n").trimEnd()}\n`;
}

export function renderKernel(ast, protocolVersion, sourceHash) {
  return `${stamp(protocolVersion, sourceHash)}\n${renderKernelBody(ast, protocolVersion)}`;
}

export function renderChapter(ast, chapter, protocolVersion, sourceHash) {
  const sections = chapter.sections.map(number => ast.sections.find(section => section.number === number)).filter(Boolean);
  const ruleIds = sections.flatMap(section => section.ruleIds);
  const lines = [
    stamp(protocolVersion, sourceHash, `Chapter: ${chapter.id}.`),
    `# Prumo chapter — ${chapter.title}`,
    "",
    `Chapter \`${chapter.id}\`. Rules ${ruleIds[0]} to ${ruleIds.at(-1)} (${ruleIds.length}). Loaded when: ${chapter.triggers.map(trigger => trigger.description).join("; ")}.${chapter.nonSuppressible ? " This chapter is never suppressed once triggered." : ""}`,
    ""
  ];
  for (const section of sections) lines.push(sectionMarkdown(section), "", "---", "");
  while (lines.at(-1) === "" || lines.at(-1) === "---") lines.pop();
  return `${lines.join("\n")}\n`;
}

export function managedBlock(body, protocolVersion) {
  const content = `${body.trimEnd()}\n`;
  const hash = sha256(content);
  return { text: `${MANAGED_BEGIN} protocol=${protocolVersion} hash=${hash} -->\n${content}${MANAGED_END}\n`, hash };
}

export function renderAgentBridge(ast, protocolVersion, sourceHash, variant) {
  const kernel = renderKernelBody(ast, protocolVersion);
  const block = managedBlock(kernel, protocolVersion);
  const header = `${stamp(protocolVersion, sourceHash, `Read by: ${variant.consumers}.`)}\n`;
  if (variant.frontMatter) return `${variant.frontMatter}\n${header}\n${block.text}`;
  return `${header}\n${block.text}`;
}

